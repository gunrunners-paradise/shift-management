/* SQLite schema for the fork's policies. Distinct version prevents opening a
 * Mishmoret database as if its periods and closure semantics were compatible. */
static const char *schema_sql =
    "BEGIN IMMEDIATE;"
    "CREATE TABLE users(id INTEGER PRIMARY KEY,login TEXT UNIQUE NOT NULL,name TEXT NOT NULL,"
    "first_name TEXT NOT NULL,last_name TEXT NOT NULL,gender TEXT NOT NULL DEFAULT "
    "'other',birth_date TEXT,"
    "role TEXT NOT NULL CHECK(role IN('admin','member')),active INTEGER NOT NULL DEFAULT 1 "
    "CHECK(active IN(0,1)),"
    "password TEXT NOT NULL,must_change INTEGER NOT NULL DEFAULT 0);"
    "CREATE TABLE avatars(user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,type "
    "TEXT NOT NULL,data BLOB NOT NULL);"
    "CREATE TABLE sessions(hash TEXT PRIMARY KEY,user_id INTEGER NOT NULL REFERENCES users(id) ON "
    "DELETE CASCADE,csrf TEXT NOT NULL,expires INTEGER NOT NULL);"
    "CREATE INDEX sessions_user ON sessions(user_id);"
    "CREATE TABLE shifts(id INTEGER PRIMARY KEY,worker_id INTEGER NOT NULL REFERENCES "
    "users(id),shift_date TEXT NOT NULL,"
    "period TEXT NOT NULL CHECK(period IN('09_13','10_14','11_15','12_16','full')),cancelled_at "
    "TEXT,"
    "cancelled_by INTEGER REFERENCES users(id) ON DELETE SET NULL,cancellation_reason "
    "TEXT,cancellation_note TEXT,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);"
    "CREATE UNIQUE INDEX shifts_one_active ON shifts(worker_id,shift_date) WHERE cancelled_at IS "
    "NULL;"
    "CREATE INDEX shifts_date ON shifts(shift_date,cancelled_at);"
    "CREATE TABLE blocked_dates(date TEXT PRIMARY KEY,reason TEXT,blocked_by INTEGER REFERENCES "
    "users(id) ON DELETE SET NULL);"
    "CREATE TABLE desks(id INTEGER PRIMARY KEY,name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT "
    "1);"
    "CREATE TABLE desk_reservations(id INTEGER PRIMARY KEY,worker_id INTEGER NOT NULL REFERENCES "
    "users(id),desk_id INTEGER NOT NULL REFERENCES desks(id),"
    "reservation_date TEXT NOT NULL,start_time TEXT NOT NULL,end_time TEXT NOT NULL,cancelled_at "
    "TEXT,cancelled_by INTEGER REFERENCES users(id) ON DELETE SET NULL,"
    "cancellation_reason TEXT,cancellation_note TEXT,created_at TEXT NOT NULL DEFAULT "
    "CURRENT_TIMESTAMP,"
    "CHECK(start_time>='09:00' AND end_time<='16:30' AND start_time<end_time));"
    "CREATE UNIQUE INDEX desks_one_active ON desk_reservations(worker_id,reservation_date) WHERE "
    "cancelled_at IS NULL;"
    "CREATE INDEX desk_intervals ON desk_reservations(desk_id,reservation_date,cancelled_at);"
    "CREATE TABLE events(id INTEGER PRIMARY KEY,date TEXT NOT NULL,title TEXT NOT NULL,kind TEXT "
    "NOT NULL CHECK(kind IN('event','holiday')),description TEXT NOT NULL DEFAULT '');"
    "CREATE TABLE receipts(worker_id INTEGER NOT NULL REFERENCES users(id),month TEXT NOT "
    "NULL,has_receipts INTEGER NOT NULL CHECK(has_receipts IN(0,1)),PRIMARY KEY(worker_id,month));"
    "CREATE TABLE signup_settings(role TEXT PRIMARY KEY CHECK(role IN('admin','member')),enabled "
    "INTEGER NOT NULL DEFAULT 0);"
    "INSERT INTO signup_settings(role) VALUES('admin'),('member');"
    "CREATE TABLE pending_signups(id INTEGER PRIMARY KEY AUTOINCREMENT,login TEXT UNIQUE NOT NULL,first_name "
    "TEXT NOT NULL,last_name TEXT NOT NULL,gender TEXT NOT NULL,birth_date TEXT,"
    "role TEXT NOT NULL CHECK(role IN('admin','member')),password TEXT NOT NULL,created_at TEXT "
    "NOT NULL DEFAULT CURRENT_TIMESTAMP);"
    "CREATE TABLE signup_reviews(token TEXT PRIMARY KEY,actor_id INTEGER NOT NULL REFERENCES "
    "users(id) ON DELETE CASCADE,session_hash TEXT NOT NULL,action TEXT NOT NULL,ids TEXT NOT "
    "NULL,expires INTEGER NOT NULL);"
    "CREATE TABLE audit(id INTEGER PRIMARY KEY,at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,user_id "
    "INTEGER,action TEXT NOT NULL,target_id INTEGER);"
    "ALTER TABLE pending_signups ADD COLUMN review_error TEXT;"
    "PRAGMA user_version=101;";

/* Old review tokens may already refer to reused IDs. Invalidate those tokens
 * while retaining every pending request and its ID; managers review again. */
static const char *signup_identity_migration_sql =
    "BEGIN IMMEDIATE;"
    "CREATE TABLE pending_signups_v101(id INTEGER PRIMARY KEY AUTOINCREMENT,"
    "login TEXT UNIQUE NOT NULL,first_name TEXT NOT NULL,last_name TEXT NOT NULL,"
    "gender TEXT NOT NULL,birth_date TEXT,role TEXT NOT NULL CHECK(role IN('admin','member')),"
    "password TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,review_error TEXT);"
    "INSERT INTO pending_signups_v101 SELECT id,login,first_name,last_name,gender,birth_date,"
    "role,password,created_at,review_error FROM pending_signups;"
    "DROP TABLE pending_signups;"
    "ALTER TABLE pending_signups_v101 RENAME TO pending_signups;"
    "DELETE FROM signup_reviews;"
    "PRAGMA user_version=101;"
    "COMMIT;";
